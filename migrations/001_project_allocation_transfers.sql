ALTER TABLE inventory_allocations
    ADD COLUMN IF NOT EXISTS transferred_out_quantity NUMERIC(14,3) NOT NULL DEFAULT 0;
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'inventory_allocations_transferred_out_check'
    ) THEN
        ALTER TABLE inventory_allocations
            ADD CONSTRAINT inventory_allocations_transferred_out_check
            CHECK (transferred_out_quantity >= 0 AND transferred_out_quantity <= allocated_quantity);
    END IF;
END $$;
CREATE TABLE IF NOT EXISTS project_allocation_transfers (
    transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_code VARCHAR(40) NOT NULL UNIQUE,
    source_allocation_id BIGINT NOT NULL REFERENCES inventory_allocations (allocation_id),
    target_allocation_id BIGINT NOT NULL REFERENCES inventory_allocations (allocation_id),
    source_requirement_line_id BIGINT NOT NULL REFERENCES project_material_requirements (requirement_line_id),
    target_requirement_line_id BIGINT NOT NULL REFERENCES project_material_requirements (requirement_line_id),
    source_project_id BIGINT NOT NULL REFERENCES projects (project_id),
    target_project_id BIGINT NOT NULL REFERENCES projects (project_id),
    material_id BIGINT NOT NULL REFERENCES materials (material_id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouses (warehouse_id),
    quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    transferred_by_user_id BIGINT NOT NULL REFERENCES users (user_id),
    transferred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    notes TEXT NOT NULL DEFAULT '',
    CHECK (source_project_id <> target_project_id)
);
CREATE INDEX IF NOT EXISTS idx_project_allocation_transfers_source
    ON project_allocation_transfers (source_project_id, transferred_at DESC);
CREATE INDEX IF NOT EXISTS idx_project_allocation_transfers_target
    ON project_allocation_transfers (target_project_id, transferred_at DESC);